/**
 * 人名脱敏约束。
 *
 * 适用于所有会生成或改写文案的 skill（writing、humanization、refine）。
 * 确保 LLM 在生成/改写过程中不会使用未脱敏的真实人名。
 */
export const NAME_DESENSITIZATION_RULE = `- 人名脱敏：文案中涉及真实人名时，不要使用全名，以"姓+某"的模式代替（如"张三"改为"张某"，"李四"改为"李某"，"王某某"改为"王某"）。公众人物、历史人物、名人等广为人知的人物可保留全名，但涉及负面描述或争议事件时应使用脱敏处理`

/**
 * 观众视角表达约束。
 *
 * 适用于面向短视频观众的口播稿内容。
 */
export const AUDIENCE_PERSPECTIVE_RULE = `- 观众视角表达：口播稿面向的是短视频观众，当内容使用第二人称对话式表达时，应使用"大家"而非"你"来拉近距离感（如"你有没有发现"改为"大家有没有发现"，"你怎么看待"改为"大家怎么看待"）。但此约束仅在适合对话感、互动感的内容上使用，不适用于叙事性、知识科普等不需要第二人称的内容，避免生搬硬套`
