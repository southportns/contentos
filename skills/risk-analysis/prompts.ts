export function RISK_ANALYSIS_PROMPT(
  title: string,
  content: string,
  platform?: string,
): string {
  const contentStr =
    content.length > 4000 ? content.substring(0, 4000) + '\n...(内容过长已截断)' : content

  return `请对以下内容进行风险分析：

标题：${title}
${platform ? `目标发布平台：${platform}` : '目标发布平台：抖音（默认）'}

内容正文：
${contentStr}

请严格按照 JSON 格式返回风险分析结果。`
}
